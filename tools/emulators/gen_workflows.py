#!/usr/bin/env python3
"""Generates .github/workflows/build-<emulator>.yml from an upstream release workflow.

Usage: gen_workflows.py <upstream release-binaries.yml> <key> <upstream repo> <default ref> <title>

The build job is kept as upstream wrote it (so their build fixes come along), reduced to the plain linux-aarch64
build, with the upstream source checked out, tools/emulators/arise_patches.py applied, the in-app updater off and
the AppImage attached to a release "<key>-<ref>" here as "<key>-linux-aarch64.AppImage".
"""
import copy
import sys
import yaml

src_path, key, repo, ref, title = sys.argv[1:6]
src = yaml.safe_load(open(src_path))
build = copy.deepcopy(src["jobs"]["build"])
build.pop("needs", None)
build["name"] = f"{title} linux-aarch64"
build["timeout-minutes"] = 150
env = build.setdefault("env", {})
for k, v in list(env.items()):
    if "needs." in str(v):
        env[k] = str(v).replace("${{ needs.name.outputs.tag }}", "${{ inputs.ref }}")
build["strategy"] = {"fail-fast": False, "matrix": {"include": [{"platform": "linux-aarch64", "runner": "ubuntu-24.04-arm"}]}}
steps = []
for st in build["steps"]:
    name = st.get("name", "")
    if name.startswith("Upload") or "after failure" in name:
        continue
    if st.get("uses", "").startswith("actions/checkout"):
        st = {"name": "Check out source", "uses": "actions/checkout@v5", "with": {"repository": repo, "ref": "${{ inputs.ref }}"}}
        steps.append(st)
        steps.append({"name": "Check out the AriseOS patches", "uses": "actions/checkout@v5",
                      "with": {"path": "_arise", "sparse-checkout": "tools/emulators"}})
        steps.append({"name": "Apply the AriseOS patches", "shell": "bash",
                      "run": "set -euo pipefail\npython3 _arise/tools/emulators/arise_patches.py\n"})
        continue
    if name.startswith("Configure Linux"):
        st["run"] = st["run"].replace("-DENABLE_UPDATE_CHECKER=ON", "-DENABLE_UPDATE_CHECKER=OFF")
    steps.append(st)
steps.append({"name": "Publish the AppImage on AriseOS", "shell": "bash", "env": {"GH_TOKEN": "${{ github.token }}"}, "run": f'''set -euo pipefail
src=$(ls -1 *.AppImage | head -1)
test -s "$src"
asset="{key}-linux-aarch64.AppImage"
cp "$src" "$asset"
tag="{key}-${{{{ inputs.ref }}}}"
if gh release view "$tag" -R "$GITHUB_REPOSITORY" >/dev/null 2>&1; then
  gh release upload "$tag" "$asset" -R "$GITHUB_REPOSITORY" --clobber
else
  gh release create "$tag" "$asset" -R "$GITHUB_REPOSITORY" --prerelease --latest=false \\
    --title "{title} ${{{{ inputs.ref }}}} (AriseOS build) Linux ARM64" \\
    --notes "{title} ${{{{ inputs.ref }}}} from {repo}, built by AriseOS for Linux ARM64 with tools/emulators/arise_patches.py."
fi
echo "Published $asset on $tag" >> "$GITHUB_STEP_SUMMARY"
'''})
build["steps"] = steps
wf = {"name": f"Build {title} (AriseOS) for Linux ARM64",
      "on": {"workflow_dispatch": {"inputs": {"ref": {"description": f"Tag or branch of {repo}", "required": True, "default": ref}}}},
      "permissions": {"contents": "write"}, "jobs": {"build": build}}


def str_rep(dumper, data):
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


yaml.add_representer(str, str_rep)
out = yaml.dump(wf, sort_keys=False, width=200, allow_unicode=True).replace("'on':", "on:", 1)
sys.stdout.write(f"# Generated by tools/emulators/gen_workflows.py from {repo}'s release workflow. To take a newer upstream build\n"
                 f"# system, regenerate; to build a newer version, run this workflow with its tag.\n" + out)
